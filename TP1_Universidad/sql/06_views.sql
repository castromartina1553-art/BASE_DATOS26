CREATE VIEW VW_PRESTAMOS_DETALLE AS 
SELECT P.FECHA_P,CONCAT(E.NOMBRES,' ', E.APELLIDOS) AS NOMBRE_ESTUDIANTE, L.TITULO,CONCAT(F.NOMBRES,' ',F.APELLIDOS) AS NOMBRE_FUNCIONARIO, CA.NOMBRE
FROM PRESTAMO AS P
JOIN ESTUDIANTES AS E ON P.RUT_EST = E.RUT_EST
JOIN LIBROS AS L ON P.COD_LIBRO = L.COD_LIBRO
JOIN FUNCIONARIOS AS F ON P.RUT_FUNC = F.RUT_FUNC
JOIN CARRERAS AS CA ON E.ID_CARRERA = CA.ID_CARRERA;

CREATE VIEW VW_LIBROS_POR_BIBLOTECA AS 
SELECT B.NOMBRE, COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM BIBLIOTECA AS B
JOIN LIBROS AS L ON B.ID_BIBLIO = L.ID_BIBLIO
GROUP BY B.NOMBRE;