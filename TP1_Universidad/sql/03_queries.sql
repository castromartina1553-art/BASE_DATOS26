1_
SELECT TITULO, ANIO
FROM LIBROS
ORDER BY ANIO ASC;

2_
SELECT NOMBRES, APELLIDOS, EDAD
FROM ESTUDIANTES
WHERE EDAD > 25;

3_
SELECT TITULO, ANIO
FROM LIBROS
WHERE ID_EDIT = 3;

4_
SELECT *
FROM AUTORES
WHERE APELLIDOS LIKE '%M%';

5_
SELECT NOMBRES, APELLIDOS
FROM FUNCIONARIOS
WHERE SALUD != 'Buena';

6_
SELECT TITULO, A.NOMBRE, A.APELLIDOS
FROM LIBROS AS L
JOIN AUTORES AS A ON L.RUT_AUTOR = A.RUT_AUTOR;

7_
SELECT P.FECHA_P, E.NOMBRES, E.APELLIDOS, L.TITULO, F.NOMBRES, F.APELLIDOS
FROM PRESTAMO AS P
JOIN ESTUDIANTES AS E ON P.RUT_EST = E.RUT_EST 
JOIN LIBROS AS L ON P.COD_LIBRO = L.COD_LIBRO
JOIN FUNCIONARIOS AS F ON P.RUT_FUNC = F.RUT_FUNC;

8_
SELECT E.NOMBRES,E.APELLIDOS, C.NOMBRE AS CARRERA, CI.NOMBRE AS CIUDAD
FROM ESTUDIANTES AS E
JOIN CARRERAS AS C ON E.ID_CARRERA = C.ID_CARRERA
JOIN CAMPUS AS CA ON C.ID_CAMPUS = CA.ID_CAMPUS
JOIN CIUDAD AS CI ON CA.ID_CIUDAD = CI.ID_CIUDAD;

9_
SELECT L.TITULO, E.NOMBRE, E.PAIS
FROM LIBROS AS L
JOIN EDITORIALES AS E ON L.ID_EDIT = E.ID_EDIT;

10_
SELECT L.TITULO, B.NOMBRE
FROM LIBROS AS L
JOIN BIBLIOTECA AS B ON L.ID_BIBLIO = B.ID_BIBLIO;

11_
SELECT T.TIPO_L, COUNT(L.COD_LIBRO) AS CANTIDAD
FROM TIPO AS T
JOIN LIBROS AS L ON T.ID_TIPO = L.ID_TIPO
GROUP BY T.ID_TIPO, T.TIPO_L;

12_
SELECT C.NOMBRE, AVG(E.EDAD) AS PROMEDIO
FROM CARRERAS AS C
JOIN ESTUDIANTES AS E ON C.ID_CARRERA = E.ID_CARRERA
GROUP BY C.ID_CARRERA, C.NOMBRE

13_
SELECT F.NOMBRES, F.APELLIDOS, COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM FUNCIONARIOS AS F
JOIN PRESTAMO AS P ON F.RUT_FUNC = P.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRES, F.APELLIDOS
ORDER BY TOTAL_PRESTAMOS DESC;

14_
SELECT A.NOMBRE, A.APELLIDOS, COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM AUTORES AS A
JOIN LIBROS AS L ON A.RUT_AUTOR = L.RUT_AUTOR
GROUP BY A.RUT_AUTOR, A.NOMBRE, A.APELLIDOS
HAVING COUNT(L.COD_LIBRO) > 1;

15_
SELECT CI.NOMBRE AS CIUDAD, COUNT(E.RUT_EST) AS CANTIDAD_ESTUDIANTE
FROM CIUDAD AS CI
JOIN CAMPUS AS CA ON CI.ID_CIUDAD = CA.ID_CIUDAD
JOIN CARRERAS AS CAR ON CA.ID_CAMPUS = CAR.ID_CAMPUS
JOIN ESTUDIANTES AS E ON CAR.ID_CARRERA = E.ID_CARRERA
GROUP BY CI.NOMBRE;

16_
SELECT L.TITULO, L.ANIO
FROM LIBROS AS L
ORDER BY ANIO ASC;

17_
SELECT E.NOMBRES, E.APELLIDOS
FROM ESTUDIANTES AS E
JOIN PRESTAMO AS P ON E.RUT_EST = P.RUT_EST
WHERE P.RUT_EST IS NULL;

18_
SELECT L.TITULO
FROM PRESTAMO AS P
JOIN LIBROS AS L ON P.COD_LIBRO = L.COD_LIBRO
WHERE P.COD_LIBRO IS NULL;

19_
SELECT * 
FROM PRESTAMO 
WHERE MONTH(FECHA_P) = MONTH(CURRENT_DATE - INTERVAL 1 MONTH)
  AND YEAR(FECHA_P) = YEAR(CURRENT_DATE - INTERVAL 1 MONTH);

20_
SELECT L.TITULO, COUNT(L.COD_LIBRO) AS TOTAL_PRESTADO
FROM LIBROS AS L
JOIN PRESTAMO AS P ON L.COD_LIBRO = P.COD_LIBRO
GROUP BY L.TITULO;